export const SEED_STOCK: StockEntry[] = SEED_DISTRIBUTORS.flatMap((d) =>
  SEED_PRODUCTS.map((p, idx) => {
    const key = `${d.id}:${p.id}`;
    const stocked = DISTRIBUTOR_STOCK[d.id]?.includes(p.id) ?? false;
    return {
      distributorId: d.id,
      productId: p.id,
      available: stocked,
      priceOverride: d.id === "d2" && p.id === "c3" ? 118_000 : d.id === "d4" && p.id === "p2" ? 1_990_000 : undefined,
      cartonsLeft: stocked ? (LOW_STOCK[key] ?? 40 + ((idx * 37 + Number(d.id.slice(1)) * 11) % 160)) : 0,
    };
  }),
);

